package web

import "testing"

// TestFormatTimeLengthMatchesPHP 用真实 PHP 跑出的基准锁住该函数。
//
// 基准由 my_func.inc.php:94 的原文在 php8.5 下执行生成，
// 覆盖 23 个取值，重点是几个"丢数字"的缺陷分支：
//
//	6000  → "1 小时 "        （1 小时 40 分，40 分丢失）
//	7000  → "1 小时 40 秒"   （1 小时 46 分 40 秒，46 分丢失）
//	86399 → "23 小时 59 秒"  （23 小时 59 分，59 分丢失）
//	90000 → "1 天 "          （1 天 1 小时，小时丢失）
func TestFormatTimeLengthMatchesPHP(t *testing.T) {
	cases := []struct {
		in   int
		want string
	}{
		{0, "0 秒"}, {1, "1 秒"}, {9, "9 秒"}, {10, "10 秒"}, {59, "59 秒"},
		{60, "1 分 "}, {61, "1 分 01 秒"}, {69, "1 分 09 秒"}, {70, "1 分 10 秒"},
		{599, "9 分 59 秒"}, {600, "10 分 "}, {601, "10 分 01 秒"}, {660, "11 分 "},
		{3660, "1 小时 1 分 "}, {3700, "1 小时 01 分 40 秒"},
		{6000, "1 小时 "}, {7000, "1 小时 40 秒"}, {7320, "2 小时 2 分 "},
		{86399, "23 小时 59 秒"}, {86400, "1 天 "}, {90000, "1 天 "},
		{180000, "2 天 "}, {360000, "4 天 "},
	}
	for _, c := range cases {
		if got := formatTimeLength(c.in); got != c.want {
			t.Errorf("formatTimeLength(%d) = %q，期望 %q", c.in, got, c.want)
		}
	}
}
